import { mkdir, readFile, writeFile } from "node:fs/promises";
const dist = new URL("./dist/", import.meta.url);
let html = await readFile(new URL("index.html", dist), "utf8");
const script = /<script\b[^>]*\bsrc="([^"]+)"[^>]*><\/script>/;
const stylesheet = /<link\b[^>]*\bhref="([^"]+\.css)"[^>]*>/;
const jsPath = html.match(script)?.[1];
const cssPath = html.match(stylesheet)?.[1];
if (!jsPath || !cssPath)
  throw new Error("Expected one bundled script and stylesheet");
const js = await readFile(new URL(jsPath, dist), "utf8");
const css = await readFile(new URL(cssPath, dist), "utf8");
if (/\bfrom\s*["']\.\//.test(js))
  throw new Error("Standalone export cannot contain external chunks");
html = html.replace(
  script,
  () =>
    `<script type="module">${js.replace(/<\/script/gi, "<\\/script")}</script>`,
);
html = html.replace(stylesheet, () => `<style>${css}</style>`);
html =
  "<!-- Generated by pnpm --filter @app/architecture-guide build. Edit apps/architecture-guide/src instead. -->\n" +
  html;
await mkdir(new URL("../../docs/", import.meta.url), { recursive: true });
await writeFile(
  new URL("../../docs/architecture-guide.html", import.meta.url),
  html,
);
console.log(
  "Exported docs/architecture-guide.html (self-contained, works offline)",
);
